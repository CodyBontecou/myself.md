import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { format } from 'prettier';

export async function buildHealthReview() {
  const result = await build({
    entryPoints: ['dashboard/health-review.js'],
    bundle: true,
    minify: true,
    format: 'iife',
    platform: 'browser',
    target: ['es2022'],
    write: false,
  });
  const source = result.outputFiles[0]?.text;
  if (!source) throw new Error('Weekly review renderer build produced no JavaScript.');
  writeFileSync(
    'server/health-review-client.js',
    await format(
      `// Generated by scripts/build-health-review.js; edit dashboard/health-review.js.\nexport const healthReviewClient = ${JSON.stringify(source.replaceAll('</script', '<\\/script'))};\n`,
      { filepath: 'server/health-review-client.js', singleQuote: true, printWidth: 100 },
    ),
  );
}
if (process.argv[1]?.endsWith('/build-health-review.js')) await buildHealthReview();
