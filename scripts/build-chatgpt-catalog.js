import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { format } from 'prettier';

export async function buildChatgptCatalog() {
  const result = await build({
    entryPoints: ['dashboard/chatgpt-catalog.js'],
    bundle: true,
    minify: true,
    format: 'iife',
    platform: 'browser',
    target: ['es2022'],
    write: false,
  });
  const preview = await build({
    entryPoints: ['dashboard/chatgpt-catalog-preview.js'],
    bundle: true,
    minify: true,
    format: 'iife',
    platform: 'browser',
    target: ['es2022'],
    write: false,
  });
  const previewSource = preview.outputFiles[0]?.text;
  if (!previewSource) throw new Error('Catalog preview sizing build produced no JavaScript.');
  const source = result.outputFiles[0]?.text;
  if (!source) throw new Error('Catalog host renderer build produced no JavaScript.');
  writeFileSync(
    'server/chatgpt-catalog-client.js',
    await format(
      `// Generated by scripts/build-chatgpt-catalog.js; edit dashboard/chatgpt-catalog.js.\nexport const chatgptCatalogClient = ${JSON.stringify(source.replaceAll('</script', '<\\/script'))};\nexport const chatgptCatalogPreviewClient = ${JSON.stringify(previewSource.replaceAll('</script', '<\\/script'))};\n`,
      { filepath: 'server/chatgpt-catalog-client.js', singleQuote: true, printWidth: 100 },
    ),
  );
}
if (process.argv[1]?.endsWith('/build-chatgpt-catalog.js')) await buildChatgptCatalog();
