import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { resolve, relative, basename } from 'node:path';
import { format } from 'prettier';
import { readFile } from 'node:fs/promises';
import { sorted } from '../core/collections.js';

/** @param {string} directory @returns {string[]} */
function files(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name.startsWith('.') || entry.isSymbolicLink()) return [];
    const path = resolve(directory, entry.name);
    return entry.isDirectory() ? files(path) : entry.name.endsWith('.md') ? [path] : [];
  });
}

/** Generate a portable public snapshot; never include arbitrary vault metadata.
 * @param {boolean} [required] */
export async function buildBlog(required = false) {
  const root = resolve('content/blog');
  if (!existsSync(root)) {
    if (required || !existsSync('server/blog-content.js'))
      throw new Error('Blog vault missing. Run npm run blog:setup first.');
    console.log('Blog vault not linked; using the committed public blog snapshot.');
    return;
  }
  const today = new Date().toISOString().slice(0, 10);
  const posts = sorted(
    files(root).flatMap((path) => {
      const source = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
      const frontmatter = source.match(/^---\n([\s\S]*?)\n---(?:\n|$)/);
      if (source.startsWith('---\n') && !frontmatter)
        throw new Error(`Unclosed frontmatter: ${relative(root, path)}`);
      /** @type {Record<string, string>} */
      const metadata = {};
      for (const match of (frontmatter?.[1] ?? '').matchAll(
        /^(title|slug|date|updated|description|author|draft|publish):[ \t]*([^\n]*)$/gm,
      )) {
        const key = match[1];
        if (key) metadata[key] = (match[2] ?? '').trim().replace(/^(['"])(.*)\1$/, '$2');
      }
      if (metadata.draft === 'true' || metadata.publish === 'false') return [];
      let markdown = source
        .slice(frontmatter?.[0].length ?? 0)
        .replace(/%%[\s\S]*?%%/g, '')
        .trim();
      if (!markdown) return [];
      const name = basename(path, '.md');
      const heading = markdown.match(/^# (.+)(?:\n|$)/);
      const title = metadata.title || heading?.[1] || name;
      if (heading) markdown = markdown.slice(heading[0].length).trim();
      else if (markdown.split('\n')[0] === title) markdown = markdown.slice(title.length).trim();
      const slug =
        metadata.slug ||
        name
          .toLowerCase()
          .replace(/[^a-z0-9]+/g, '-')
          .replace(/^-|-$/g, '');
      if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) throw new Error(`Invalid blog slug: ${slug}`);
      const gitHistory = spawnSync(
        'git',
        ['-C', root, 'log', '--follow', '--format=%cs', '--', relative(root, path)],
        { encoding: 'utf8' },
      );
      const gitDates = (gitHistory.status === 0 ? gitHistory.stdout : '')
        .trim()
        .split('\n')
        .filter(Boolean);
      const date = metadata.date || name.match(/^\d{4}-\d{2}-\d{2}/)?.[0] || gitDates.at(-1);
      const updated = metadata.updated || gitDates[0] || date;
      for (const value of [date, updated])
        if (
          !value ||
          !/^\d{4}-\d{2}-\d{2}$/.test(value) ||
          new Date(value).toISOString().slice(0, 10) !== value
        )
          throw new Error(`Set a valid date: YYYY-MM-DD in ${relative(root, path)}`);
      if (!date || !updated || date > today) return [];
      if (updated < date) throw new Error(`Updated date precedes publication: ${slug}`);
      const excerpt = (
        markdown.split(/\n\s*\n/).find((block) => !block.startsWith('#')) || markdown
      )
        .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
        .replace(/[#*_`>\n]/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();
      const description =
        metadata.description ||
        (excerpt.length > 180 ? `${excerpt.slice(0, 180).replace(/\s+\S*$/, '')}…` : excerpt);
      return [
        {
          slug,
          title,
          date,
          updated,
          description,
          author: metadata.author || 'Cody Bontecou',
          markdown,
          source: relative(root, path).replaceAll('\\', '/'),
          minutes: Math.max(1, Math.ceil(markdown.split(/\s+/).length / 220)),
        },
      ];
    }),
    (a, b) => b.date.localeCompare(a.date) || a.title.localeCompare(b.title),
  );
  if (new Set(posts.map((post) => post.slug)).size !== posts.length)
    throw new Error('Duplicate blog slugs. Set unique slug properties in Obsidian.');
  writeFileSync(
    'server/blog-content.js',
    await format(
      `// Generated by npm run blog:build. Public body and allowlisted metadata only.\nexport const blogContentHash = '${createHash('sha256').update(JSON.stringify(posts)).digest('hex')}';\nexport const blogPosts = ${JSON.stringify(posts, null, 2)};\n`,
      {
        ...JSON.parse(await readFile(new URL('../.prettierrc.json', import.meta.url), 'utf8')),
        filepath: 'server/blog-content.js',
      },
    ),
  );
  console.log(`Built ${posts.length} public blog posts.`);
}

if (process.argv.includes('--required')) await buildBlog(true);
