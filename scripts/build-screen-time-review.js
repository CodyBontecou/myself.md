import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { format } from 'prettier';

export async function buildScreenTimeReview() {
  const result = await build({
    entryPoints: ['dashboard/screen-time-review.js'],
    bundle: true,
    minify: true,
    format: 'iife',
    platform: 'browser',
    target: ['es2022'],
    write: false,
  });
  const source = result.outputFiles[0]?.text;
  if (!source) throw new Error('Weekly review renderer build produced no JavaScript.');
  writeFileSync(
    'server/screen-time-review-client.js',
    await format(
      `// Generated by scripts/build-screen-time-review.js; edit dashboard/screen-time-review.js.\nexport const screenTimeReviewClient = ${JSON.stringify(source.replaceAll('</script', '<\\/script'))};\n`,
      { filepath: 'server/screen-time-review-client.js', singleQuote: true, printWidth: 100 },
    ),
  );
}
if (process.argv[1]?.endsWith('/build-screen-time-review.js')) await buildScreenTimeReview();
