import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { format } from 'prettier';

export async function buildHeartRateContext() {
  const result = await build({
    entryPoints: ['dashboard/heart-rate-context.js'],
    bundle: true,
    minify: true,
    format: 'iife',
    platform: 'browser',
    target: ['es2022'],
    write: false,
  });
  const source = result.outputFiles[0]?.text;
  if (!source) throw new Error('Location review renderer build produced no JavaScript.');
  writeFileSync(
    'server/heart-rate-context-client.js',
    await format(
      `// Generated by scripts/build-heart-rate-context.js; edit dashboard/heart-rate-context.js.\nexport const heartRateContextClient = ${JSON.stringify(source.replaceAll('</script', '<\\/script'))};\n`,
      { filepath: 'server/heart-rate-context-client.js', singleQuote: true, printWidth: 100 },
    ),
  );
}
if (process.argv[1]?.endsWith('/build-heart-rate-context.js')) await buildHeartRateContext();
